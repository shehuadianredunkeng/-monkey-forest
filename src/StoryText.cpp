#include "StoryText.h"

std::string getStageIntroductionText(int stage) {
    switch (stage) {
    case 1:
        return "【第一阶段：树冠试炼·第一年春夏】\n"
               "青木谷的新叶刚刚展开。你还是族群里最年轻的成员，猴王岩背却决定让你第一次"
               "独自承担寻找食物的任务。这次试炼不仅关系到储粮，也决定族群是否愿意在未来的"
               "危机中相信你的判断。前往果实森林，完成树冠试炼。";
    case 2:
        return "【第二阶段：寒潮抉择·第一年秋冬】\n"
               "你从树冠带回的收获让族群度过了夏天，但寒风比往年来得更早。猴王树下的储粮"
               "迅速减少，幼猴和守卫都在等待分配。此前赢得的信任将在这次短缺中接受考验。"
               "返回猴王树，决定族群怎样度过寒潮。";
    case 3:
        return "【第三阶段：蓝光追踪·第二年春夏】\n"
               "族群刚熬过寒冬，清泉河谷的水位却开始下降，河面泛起不自然的蓝光。顺着银色"
               "管线和回声山洞调查，你将发现这不是普通旱灾：某种陌生设备正在地下抽取青木谷"
               "的资源，而理解水声、碑文和晶片会成为日后智取敌人的基础。";
    case 4:
        return "【第四阶段：路线分歧·第二年秋冬】\n"
               "山洞中的晶片证明，来者是寻找青木晶的星猿。第二个旱季逼近，猴群必须在训练"
               "守卫、研究技术和寻找新家园之间作出准备。你的选择会形成反击、智取或迁徙路线，"
               "随后还要返回猴王树平息族群争执。";
    case 5:
        return "【第五阶段：基地潜入·第三年春夏】\n"
               "族群暂时统一了行动，通往实验基地的道路已经打开。巡逻机封锁能源室，完整抽取"
               "日志藏在控制台中。你可以正面突破、借晶片伪装权限，或依靠闪尾协助，但无论采用"
               "哪种方式，都必须取得日志才能看清赫兹的完整计划。";
    case 6:
        return "【第六阶段：家园抉择·第三年决战】\n"
               "完整日志揭示抽取塔即将永久改变地下水脉，星猿工程官赫兹已经启动倒计时。现在"
               "不是只凭一个数值选择结局：此前的守卫训练、技术研究、同伴信任和迁徙物资，"
               "将共同决定你能否反击、智取或带领族群有准备地离开。返回猴王树作出最终选择。";
    default:
        return "未知阶段。";
    }
}

std::string getEndingTextById(const std::string& endingId) {
    if (endingId == "ending_resist") {
        return "【结局：青木英雄】\n"
               "此前训练的守卫守住河谷入口，受你帮助过的同伴把补给送到前线。你与赫兹的决战"
               "为猴群争取到关闭抽取塔的时间，最后一台设备终于在火花中停下。\n"
               "星猿飞船离开后，雨水重新落进河谷。岩背把新一季的第一枚青果递给你。这次胜利"
               "并非一场孤勇，而是你一路积累的声望、力量与族群信任共同守住了家园。";
    }
    if (endingId == "ending_hack") {
        return "【结局：无声胜利】\n"
               "从河谷管线、回声碑文到星猿晶片，你把三年来理解的规律与完整日志重新组合，"
               "让抽取程序把青木谷识别为不可开采的生命保护区。所有设备同时熄灭，赫兹第一次"
               "认真看向森林，而不是地下的矿物。\n"
               "没有战火，也没有伤亡，只有清泉重新流动的声音。青木谷用一路积累的知识证明，"
               "智慧不是绕开困难，而是找到让敌人再也无法伤害家园的方法。";
    }
    if (endingId == "ending_migrate") {
        return "【结局：向南的新生】\n"
               "此前勘察的新河谷、分批储备的食物与藤索让迁徙不再是一场仓促逃亡。你安排守卫"
               "断后、闪尾引路，带着幼猴和老人越过最后一道山脊，青木谷的树冠在身后渐渐变成"
               "一条深绿色的线。\n"
               "族群最终安全抵达新河谷，并在河边埋下最后一颗青木种子。离开不是失败，也不是"
               "遗忘，而是你用准备和领导让猴群保住了未来。";
    }
    if (endingId == "ending_fail") {
        return "【结局：失落之谷】\n"
               "当食物、水源、生命或关键准备不足以支撑最后行动时，猴群错过了关闭抽取塔的"
               "机会。树冠上的回应逐渐消失，银色设备仍在黑夜中运转。\n"
               "青木谷没有等到下一个春天。这个结局提醒后来者：最后的选择从来不只发生在"
               "决战一刻，而是由此前每一次准备、帮助和取舍共同写成。";
    }
    return "未找到对应的结局文本，请继续推进主线或重新检查结局条件。";
}
