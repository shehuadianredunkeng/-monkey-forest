const EndingInfo* findEndingInfo(const string& endingId) {
    for (const EndingInfo& info : allEndingInfos()) {
        if (info.id == endingId) {
            return &info;
        }
    }
    return nullptr;
}

string composeEndingText(const EndingInfo& info, const string& body) {
    return "【" + info.heading + "】\n" +
           "[" + info.conditionTag + "：" + info.condition + "]\n" +
           body + "\n" +
           "[结局评价：" + info.evaluation + "]";
}

