string getEndingTextById(const string& endingId) {
    const EndingInfo* info = findEndingInfo(endingId);
    if (info == nullptr) {
        return "未找到对应的结局文本，请继续推进主线或重新检查结局条件。";
    }
    return composeEndingText(*info, info->body);
}
