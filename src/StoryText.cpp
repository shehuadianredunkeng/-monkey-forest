#include "StoryText.h"

std::string getStageIntroductionText(int stage) {
    switch (stage) {
    case 1:
        return "【第一年·春夏】\n"
               "青木谷的新叶刚刚展开。你还是族群里最年轻的成员，但岩背决定让你第一次独自寻找食物。"
               "果林、河谷和树冠都在等待探索。";
    case 2:
        return "【第一年·秋冬】\n"
               "寒风比往年来得更早，猴王树下的储粮迅速减少。族群第一次把生存的压力放到你的肩上。";
    case 3:
        return "【第二年·春夏】\n"
               "河水泛起蓝光，夜空中出现规律移动的亮点。闪尾说，那些脚印像猴子，却没有任何气味。";
    case 4:
        return "【第二年·秋冬】\n"
               "干旱持续，陌生设备开始在山洞深处运转。守卫家园还是准备迁徙，猴群内部出现了分歧。";
    case 5:
        return "【第三年·春夏】\n"
               "实验基地彻底苏醒，银色管线从地下抽走青木晶。果林正在枯萎，你必须进入基地找出阻止它的方法。";
    case 6:
        return "【第三年·决战】\n"
               "傲慢的星猿工程官赫兹已经完成倒计时。青木谷只剩最后一次选择：反击、智取，或者迁徙。";
    default:
        return "未知阶段。";
    }
}

std::string getEndingTextById(const std::string& endingId) {
    if (endingId == "ending_resist") {
        return "【结局：青木英雄】\n"
               "最后一台抽取设备在火花中停下。赫兹倒下后，星猿飞船离开青木谷。"
               "雨水重新落进河谷，岩背把新一季的第一枚青果递给你。"
               "这一次，你不再是跟在队伍末尾的幼猴，而是守住家园的领袖。";
    }
    if (endingId == "ending_hack") {
        return "【结局：无声胜利】\n"
               "你把完整日志写回抽取程序，所有设备同时熄灭。赫兹第一次认真看向森林，而不是地下的矿物。"
               "没有欢呼震动山谷，只有清泉重新流动的声音。青木谷用智慧证明，这里从来不是一片无主之地。";
    }
    if (endingId == "ending_migrate") {
        return "【结局：向南的新生】\n"
               "猴群越过最后一道山脊时，青木谷的树冠正在身后变成一条深绿色的线。"
               "你们依靠准备好的藤索、药草和食物抵达新河谷，并在河边埋下最后一颗青木种子。"
               "离开不是遗忘，而是让族群继续活下去。";
    }
    if (endingId == "ending_fail") {
        return "【结局：失落之谷】\n"
               "食物、水源或生命终于耗尽，树冠上的回应逐渐消失。银色设备仍在黑夜中运转。"
               "青木谷没有等到下一个春天，但风穿过空荡树枝时，仍像在重复那场未完成的选择。";
    }
    return "未找到对应的结局文本：" + endingId;
}
