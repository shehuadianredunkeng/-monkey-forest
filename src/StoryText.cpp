#include "StoryText.h"

std::string getStageIntroductionText(int stage) {
    switch (stage) {
    case 1:
        return "【第一阶段：树冠试炼·第一年春夏】\n"
               "青木谷的新叶刚刚展开。你还是族群里最年轻的成员，猴王岩背却决定让你第一次"
               "独自承担寻找食物的任务。这次试炼不仅关系到储粮，也决定族群是否愿意在未来的"
               "危机中相信你的判断。前往果实森林，完成树冠试炼。";
    case 2:
        return "【第二阶段：寒潮抉择·第一年秋冬】\n"
               "你从树冠带回的收获让族群度过了夏天，但寒风比往年来得更早。猴王树下的储粮"
               "迅速减少，幼猴和守卫都在等待分配。此前赢得的信任将在这次短缺中接受考验。"
               "返回猴王树，决定族群怎样度过寒潮。";
    case 3:
        return "【第三阶段：蓝光追踪·第二年春夏】\n"
               "族群刚熬过寒冬，清泉河谷的水位却开始下降，河面泛起不自然的蓝光。顺着银色"
               "管线和回声山洞调查，你将发现这不是普通旱灾：某种陌生设备正在地下抽取青木谷"
               "的资源，而理解水声、碑文和晶片会成为日后智取敌人的基础。";
    case 4:
        return "【第四阶段：路线分歧·第二年秋冬】\n"
               "山洞中的晶片证明，来者是寻找青木晶的星猿。第二个旱季逼近，猴群必须在训练"
               "守卫、研究技术和寻找新家园之间作出准备。你的选择会形成反击、智取或迁徙路线，"
               "随后还要返回猴王树平息族群争执。";
    case 5:
        return "【第五阶段：基地潜入·第三年春夏】\n"
               "族群暂时统一了行动，通往实验基地的道路已经打开。巡逻机封锁能源室，完整抽取"
               "日志藏在控制台中。你可以正面突破、借晶片伪装权限，或依靠闪尾协助，但无论采用"
               "哪种方式，都必须取得日志才能看清赫兹的完整计划。";
    case 6:
        return "【第六阶段：家园抉择·第三年决战】\n"
               "完整日志揭示抽取塔即将永久改变地下水脉，星猿工程官赫兹已经启动倒计时。现在"
               "不是只凭一个数值选择结局：此前的守卫训练、技术研究、同伴信任和迁徙物资，"
               "将共同决定你能否反击、智取或带领族群有准备地离开。返回猴王树作出最终选择。";
    default:
        return "未知阶段。";
    }
}

std::string getEndingTextById(const std::string& endingId) {
    if (endingId == "ending_resist") {
        return "【结局：青木英雄】\n"
               "此前训练的守卫在河谷入口排成并不整齐、却一步也不肯后退的队伍。受过你帮助的同伴把草药和果实送上前线，闪尾沿着藤蔓来回传递消息，豆豆也把自己珍藏的半枚青果塞进你手里。你终于明白，所谓英雄并不是永远站在所有人前面，而是让每个普通成员都相信自己能够守住身后的家。\n"
               "与赫兹的决战拖到雨云压低树冠时，最后一台抽取设备终于在火花中停止。星猿飞船撤离后，第一场雨落进干裂河床，猴群没有欢呼太久，便开始修桥、清理管线、重新播下果核。你也没有坐上新的王座，而是继续和大家一起搬石头。岩背把新一季的第一枚青果递给你，说青木谷记住的不是一次漂亮胜利，而是你三年来每一次没有放弃同伴的选择。力量替你打开战场，信任才真正守住了家园。";
    }
    if (endingId == "ending_hack") {
        return "【结局：无声胜利】\n"
               "从河谷管线的蓝光、回声山洞的碑文到星猿晶片上的细小纹路，你把三年来看似零散的发现逐一拼回完整图景。控制台不断弹出警告，赫兹坚信一只本地吗喽不可能理解星际协议，你却在最后一刻改写了资源识别规则，让系统第一次把青木谷标记为拥有文明、记忆与不可替代生命关系的保护区。\n"
               "抽取塔没有爆炸，只是一盏接一盏安静熄灭。没有守卫倒下，也没有谁在胜利中失去家人。赫兹走出基地，第一次抬头看见猴王树上为幼猴遮雨的枝叶，而不是计算树根下还有多少青木晶。后来星猿留下了一座公开的观测站，技术必须经过猴群同意才能使用。你把研究手册放回树洞课堂，告诉豆豆：智慧并不是用复杂的话压过别人，也不是躲开困难，而是看见隐藏的联系，让强者不得不承认弱小生命同样有决定未来的权利。";
    }
    if (endingId == "ending_migrate") {
        return "【结局：向南的新生】\n"
               "此前勘察的新河谷、分批储备的食物与一捆捆藤索，让迁徙不再是一场被恐惧推着走的逃亡。你把队伍分成照顾幼猴、寻找水源和守护后方的小组，为每一位老人安排停歇的位置，也给坚持留下的同伴画好日后汇合的标记。出发那天没有号角，大家只是依次触摸猴王树粗糙的树皮，把关于家园的记忆带在身上。\n"
               "越过最后一道山脊时，青木谷的树冠在身后缩成一条深绿色的线。有人哭了，也有人第一次对陌生南方产生期待。漫长旅途中，你学会领导不是替所有人决定，而是在争执和疲惫中让每个声音都被听见。族群最终安全抵达新河谷，在河边埋下最后一颗青木种子，并把旧家园的故事刻进新树屋。多年后，那颗种子长出第一片叶子，你终于接受：离开并不必然意味着失败，真正的守护也可以是为所爱的人保住继续生活、继续记得并重新开始的机会。";
    }
    if (endingId == "ending_fail") {
        return "【结局：失落之谷】\n"
               "伤势、枯竭的物资与尚未完成的准备在最后一刻同时追上了你。猴群试图关闭抽取塔，却既没有足够力量突破守卫，也没有知识改写系统，更没有一条能让老幼安全离开的道路。命令在混乱中失去回应，银色设备仍在黑夜里稳定运转，河床一点点露出苍白的石头。你被同伴拖回树洞时，第一次不敢看他们的眼睛。\n"
               "青木谷没有等到熟悉的下一个春天。幸存者被迫分散，有人向南，有人留在干枯树冠等待奇迹。你后来走遍许多森林，把失败经过一遍遍讲给陌生族群听，不再删去自己的犹豫和疏忽。你终于懂得，最后的选择从来不只发生在决战那一刻：是否拾起一株草药、是否帮助一个孩子、是否为看似遥远的危险提前准备，都在悄悄书写结局。失落之谷没有把你变成英雄，却让你的余生成为一封寄给后来者的警告。";
    }
    if (endingId == "ending_earth_gift") {
        return "【隐藏结局：地球的礼物】\n"
               "你把春花、蝉蜕、秋叶与落雪依次放在猴王树盘结的根系之间。四件不起眼的信物来自不同时间：初生、盛放、凋落与沉眠。你没有向某位神明请求凭空降下胜利，只是把一路看见的季节重新交还给脚下的土地。祈福声穿过根须，河谷、山洞与森林同时亮起柔和的绿色纹路，仿佛整颗星球终于回应了长期被忽略的疼痛。\n"
               "藤蔓缠住抽取塔，地下水冲开银色管线，候鸟与兽群从不同方向围住基地。赫兹的武器能够计算单个敌人的力量，却无法计算一片生态共同作出的选择。设备在自然之力中瓦解，星猿第一次意识到，他们试图带走的从来不是无主矿物，而是无数生命共享的家。胜利之后，四件信物化作尘土，没有留下可炫耀的神器。你也明白地球的礼物不是替你战斗的奇迹，而是当你认真珍惜每一个季节时，万物愿意与你站在一起。";
    }
    if (endingId == "ending_not_hero") {
        return "【普通结局：你不是英雄】\n"
               "最终抉择摆在面前时，你检查了背包、训练记录和同伴名单，却发现没有任何一条英雄路线真正准备完成。你没有足够声望召集反击，也未能读懂控制程序，迁徙物资更撑不起漫长旅途。过去你总以为关键时刻会自然出现一个漂亮答案，直到红色任务点在脚下熄灭，才明白准备不足本身也是一种选择。\n"
               "你没有奇迹般击败赫兹。猴群与星猿谈成了并不公平的协议：交出部分青木晶，换取河谷和猴王树暂时保留。有人埋怨你，有人庆幸至少没有更多伤亡，而你第一次允许自己同时承认羞愧与庆幸。之后的日子里，你不再等待成为传说中的英雄，而是每天记录水位、训练幼猴、修补储藏洞，为下一次危机做最普通的准备。许多年后，豆豆问这算不算失败，你回答：我不是英雄，但我仍能学着负责。真正的成长，也许正从承认自己没准备好开始。";
    }
    if (endingId == "ending_coward") {
        return "【坏结局：你是狗熊】\n"
               "第七次转身时，你已经熟悉每一条逃跑路线：哪根藤蔓最结实，哪块岩石能挡住追击，怎样落地才不会扭伤脚踝。你甚至把逃跑练得像一项值得骄傲的本领，却忘了每一次脱离战场，都有人留在原地替你承受没有结束的危险。闪尾不再从树冠出现，同伴的呼喊也渐渐变成沉默。\n"
               "当抽取塔的震动传到猴王树，你又一次本能地寻找退路，却发现身后已经没有可以继续交给别人的家园。你终于停下，但这一次不是勇敢，而是所有道路都已消失。后来有人问，聪明地撤退难道也是错误吗？当然不是。保存力量、等待时机，本来就是战斗的一部分；真正让你成为狗熊的，是把每次逃避都包装成策略，却从不回头完成应该承担的事。如果面对挑战时只会逃避，怎么守护自己想要守护的东西？这句话留在空荡的树洞里，也留给下一次重新开始的你。";
    }
    return "未找到对应的结局文本，请继续推进主线或重新检查结局条件。";
}
